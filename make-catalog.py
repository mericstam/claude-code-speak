"""Regenerates hooks/piper-voices.ts: the Piper voices sherpa-onnx publishes, by language.

    python3 make-catalog.py

Reads the asset list of https://github.com/k2-fsa/sherpa-onnx/releases/tag/tts-models.
English is left out: Kokoro reads it.
"""
import json, re, sys, urllib.request
from pathlib import Path

API = 'https://api.github.com/repos/k2-fsa/sherpa-onnx/releases'

def assets():
    release = json.load(urllib.request.urlopen(f'{API}/tags/tts-models'))
    page = 1
    while True:
        batch = json.load(urllib.request.urlopen(f'{API}/{release["id"]}/assets?per_page=100&page={page}'))
        if not batch:
            return
        for a in batch:
            yield a['name'], a['size']
        page += 1

LANGS = {  # iso639-1: (English name, native name, franc code, preferred default voice)
 'ar': ('Arabic','العربية','arb','ar_JO-kareem-medium'), 'ca': ('Catalan','Català','cat','ca_ES-upc_ona-medium'),
 'cs': ('Czech','Čeština','ces','cs_CZ-jirka-medium'), 'cy': ('Welsh','Cymraeg','cym','cy_GB-gwryw_gogleddol-medium'),
 'da': ('Danish','Dansk','dan','da_DK-talesyntese-medium'), 'de': ('German','Deutsch','deu','de_DE-thorsten-medium'),
 'el': ('Greek','Ελληνικά','ell','el_GR-rapunzelina-low'), 'es': ('Spanish','Español','spa','es_ES-davefx-medium'),
 'eu': ('Basque','Euskara','eus',None), 'fa': ('Persian','فارسی','pes','fa_IR-amir-medium'),
 'fi': ('Finnish','Suomi','fin','fi_FI-harri-medium'), 'fr': ('French','Français','fra','fr_FR-siwis-medium'),
 'hi': ('Hindi','हिन्दी','hin',None), 'hu': ('Hungarian','Magyar','hun','hu_HU-anna-medium'),
 'id': ('Indonesian','Bahasa Indonesia','ind',None), 'is': ('Icelandic','Íslenska','isl','is_IS-bui-medium'),
 'it': ('Italian','Italiano','ita','it_IT-paola-medium'), 'ka': ('Georgian','ქართული','kat',None),
 'kk': ('Kazakh','Қазақ','kaz',None), 'ku': ('Kurdish','Kurdî','ckb',None),
 'lb': ('Luxembourgish','Lëtzebuergesch','ltz',None), 'lv': ('Latvian','Latviešu','lvs',None),
 'ml': ('Malayalam','മലയാളം','mal',None), 'ne': ('Nepali','नेपाली','npi',None),
 'nl': ('Dutch','Nederlands','nld','nl_NL-pim-medium'), 'no': ('Norwegian','Norsk','nob','no_NO-talesyntese-medium'),
 'pl': ('Polish','Polski','pol','pl_PL-gosia-medium'), 'pt': ('Portuguese','Português','por','pt_BR-faber-medium'),
 'ro': ('Romanian','Română','ron',None), 'ru': ('Russian','Русский','rus','ru_RU-irina-medium'),
 'sk': ('Slovak','Slovenčina','slk',None), 'sl': ('Slovenian','Slovenščina','slv',None),
 'sq': ('Albanian','Shqip','als',None), 'sr': ('Serbian','Српски','srp',None),
 'sv': ('Swedish','Svenska','swe','sv_SE-nst-medium'), 'sw': ('Swahili','Kiswahili','swh',None),
 'tr': ('Turkish','Türkçe','tur','tr_TR-dfki-medium'), 'uk': ('Ukrainian','Українська','ukr','uk_UA-ukrainian_tts-medium'),
 'ur': ('Urdu','اردو','urd',None), 'vi': ('Vietnamese','Tiếng Việt','vie','vi_VN-vais1000-medium'),
 'zh': ('Chinese','中文','cmn','zh_CN-huayan-medium'),
}
voices = {}
for name, size in assets():
    m = re.fullmatch(r'vits-piper-(([a-z]{2})_[A-Z]{2}-[a-z0-9_]+-(x_low|low|medium|high))\.tar\.bz2', name)
    if not m: continue
    vid, lang = m.group(1), m.group(2)
    if lang not in LANGS: continue
    voices.setdefault(lang, []).append({'id': vid, 'mb': round(int(size) / 1e6)})
RANK = {'medium': 0, 'high': 1, 'low': 2, 'x_low': 3}
SILLY = re.compile(r'glados|turret|emotional|miro|dii')
out = {}
for code, (name, native, franc, pref) in sorted(LANGS.items()):
    vs = sorted(voices.get(code, []), key=lambda v: v['id'])
    ids = [v['id'] for v in vs]
    if pref not in ids:
        if pref: print('missing preferred', pref, file=sys.stderr)
        pick = sorted(vs, key=lambda v: (bool(SILLY.search(v['id'])), RANK[v['id'].rsplit('-', 1)[1]], v['id']))
        pref = pick[0]['id']
    out[code] = {'name': name, 'native': native, 'franc': franc, 'voice': pref, 'voices': vs}
target = Path(__file__).parent / 'hooks' / 'piper-voices.ts'
target.write_text(
    '// Generated by make-catalog.py from the sherpa-onnx tts-models release. Do not edit.\n\n'
    'export type PiperVoice = { id: string; mb: number }\n'
    'export type PiperLanguage = { name: string; native: string; franc: string; voice: string; voices: PiperVoice[] }\n\n'
    f'export const PIPER_LANGUAGES: Record<string, PiperLanguage> = {json.dumps(out, ensure_ascii=False, indent=2)}\n')
print(len(out), 'languages,', sum(len(v['voices']) for v in out.values()), 'voices', file=sys.stderr)
